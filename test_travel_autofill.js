const fs=require('fs'),vm=require('vm'),assert=require('assert');
const listeners={},elements={};
for(const side of ['origin','destination'])for(const suffix of ['query','choice','selected','suggestions'])elements['#'+side+'-'+suffix]={value:'',innerHTML:'',textContent:'',hidden:false};
elements['#postcode-consent']={checked:false};
let resolveSearch;
const context={state:{boot:{settings:{user_address:'Saved home'},beta:{}},tab:'transport'},escapeHtml:String,document:{addEventListener:(name,fn)=>{listeners[name]=fn},querySelector:s=>elements[s]},setTimeout,clearTimeout,clearInterval,queueMicrotask:()=>{},api:()=>new Promise(r=>resolveSearch=r)};
vm.createContext(context);vm.runInContext(fs.readFileSync('static/travel-assets.js','utf8'),context);
assert(vm.runInContext('renderTravel150()',context).includes('value="Saved home"'));
const travelMarkup=vm.runInContext('renderTravel150()',context);
assert(travelMarkup.includes('id="origin-suggestions"'));
assert(travelMarkup.includes('id="destination-suggestions"'));
assert(!travelMarkup.includes('Find places'));
assert(!travelMarkup.includes('Choose a matching place'));
(async()=>{
 elements['#origin-query'].value='Liverpool';
 const pending=vm.runInContext("searchTravelPlace150('origin')",context);
 elements['#origin-query'].value='Birkenhead';
 vm.runInContext("clearTravelPlace150('origin')",context);
 resolveSearch({places:[{name:'Liverpool',point:[53,-3]}]});await pending;
 assert(!elements['#origin-choice'].innerHTML.includes('Liverpool'));
 vm.runInContext('travel150.points.origin=[53,-3]',context);
 vm.runInContext("clearTravelPlace150('origin')",context);
 assert.equal(vm.runInContext('travel150.points.origin',context),undefined);
 context.travel150.status={provider:'OpenTripPlanner'};
 context.api=async()=>({places:[]});
 elements['#origin-query'].value='Saved home';
 await vm.runInContext("searchTravelPlace150('origin',false)",context);
 assert(!elements['#origin-choice'].innerHTML.includes('Saved home'),'OTP must not offer an un-geocoded saved address as a usable place');
 assert.match(elements['#origin-selected'].textContent,/No matching place/,'OTP must explain that a coordinate-backed suggestion is required');
 context.travel150.status={provider:'HERE'};
 await vm.runInContext("searchTravelPlace150('origin',false)",context);
 assert(elements['#origin-choice'].innerHTML.includes('Saved home'),'HERE may resolve a saved address server-side after consent');
 assert.match(elements['#origin-selected'].textContent,/HERE will locate it/);
 console.log('Travel autofill and provider-specific geocoding checks passed');
})().catch(e=>{console.error(e);process.exitCode=1});
