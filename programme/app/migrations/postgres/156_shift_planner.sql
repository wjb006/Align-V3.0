-- Restore the beta shift planner on existing V3 Neon databases.
-- Additive only: no existing tables or user data are deleted.
CREATE TABLE IF NOT EXISTS align_owner.locations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  address text NOT NULL DEFAULT '',
  colour text NOT NULL DEFAULT '#365CE6',
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS align_owner.shift_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  colour text NOT NULL DEFAULT '#3B82F6',
  active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS align_owner.location_shift_types (
  location_id bigint NOT NULL REFERENCES align_owner.locations(id) ON DELETE CASCADE,
  shift_type_id bigint NOT NULL REFERENCES align_owner.shift_types(id) ON DELETE CASCADE,
  PRIMARY KEY(location_id,shift_type_id)
);
CREATE TABLE IF NOT EXISTS align_owner.shift_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id bigint NOT NULL REFERENCES align_owner.locations(id) ON DELETE RESTRICT,
  shift_type_id bigint NOT NULL REFERENCES align_owner.shift_types(id) ON DELETE RESTRICT,
  label text NOT NULL,
  sub_shift_type text NOT NULL DEFAULT '',
  start_time text NOT NULL,
  end_time text NOT NULL,
  break_minutes integer NOT NULL DEFAULT 0,
  applicable_days text NOT NULL DEFAULT '[]',
  active integer NOT NULL DEFAULT 1,
  UNIQUE(location_id,label)
);
CREATE TABLE IF NOT EXISTS align_owner.shifts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_date text NOT NULL,
  template_id bigint REFERENCES align_owner.shift_templates(id) ON DELETE SET NULL,
  location_id bigint REFERENCES align_owner.locations(id) ON DELETE SET NULL,
  shift_type_id bigint REFERENCES align_owner.shift_types(id) ON DELETE SET NULL,
  location_name text NOT NULL,
  shift_type_name text NOT NULL,
  colour text NOT NULL,
  start_time text NOT NULL,
  end_time text NOT NULL,
  break_minutes integer NOT NULL DEFAULT 0,
  hours real NOT NULL,
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_shifts_date ON align_owner.shifts(work_date);
CREATE INDEX IF NOT EXISTS idx_shifts_template ON align_owner.shifts(template_id);
CREATE TABLE IF NOT EXISTS align_owner.shift_batches (
  request_id text PRIMARY KEY,
  payload_hash text NOT NULL DEFAULT '',
  result_json text NOT NULL
);
CREATE TABLE IF NOT EXISTS align_owner.annual_leave (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leave_date text NOT NULL UNIQUE,
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_leave_date ON align_owner.annual_leave(leave_date);
CREATE TABLE IF NOT EXISTS align_owner.alert_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  minutes_before integer NOT NULL CHECK(minutes_before BETWEEN 0 AND 10080),
  active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS align_owner.alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id bigint NOT NULL REFERENCES align_owner.shifts(id) ON DELETE CASCADE,
  title text NOT NULL,
  alert_at text NOT NULL,
  status text NOT NULL DEFAULT 'pending'
);
CREATE INDEX IF NOT EXISTS idx_alerts_time ON align_owner.alerts(alert_at,status);

