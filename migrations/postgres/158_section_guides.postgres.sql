-- Guided section setup for an existing hosted schema.
-- Idempotent. Apply to align_owner and each align_tester schema. The app does not run this file.
CREATE TABLE IF NOT EXISTS align_owner.saved_places (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL DEFAULT '',
    location text NOT NULL DEFAULT '',
    section_id bigint REFERENCES align_owner.organiser_sections(id) ON DELETE CASCADE,
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_saved_places_section ON align_owner.saved_places(section_id, LOWER(name), LOWER(location));

CREATE TABLE IF NOT EXISTS align_owner.planner_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    colour text NOT NULL DEFAULT '#16D9F2',
    created_at text NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_planner_labels_name ON align_owner.planner_labels(LOWER(name));

CREATE TABLE IF NOT EXISTS align_owner.section_defaults (
    section_id bigint PRIMARY KEY REFERENCES align_owner.organiser_sections(id) ON DELETE CASCADE,
    place_id bigint REFERENCES align_owner.saved_places(id) ON DELETE SET NULL,
    travel_minutes integer NOT NULL DEFAULT 30 CHECK (travel_minutes BETWEEN 0 AND 10080),
    travel_mode text NOT NULL DEFAULT 'transit',
    travel_info text NOT NULL DEFAULT '',
    leave_alert_minutes integer NOT NULL DEFAULT 0 CHECK (leave_alert_minutes BETWEEN 0 AND 10080),
    reminder_minutes integer NOT NULL DEFAULT 0 CHECK (reminder_minutes BETWEEN 0 AND 10080)
);

CREATE TABLE IF NOT EXISTS align_owner.organiser_event_details (
    event_id bigint PRIMARY KEY REFERENCES align_owner.organiser_events(id) ON DELETE CASCADE,
    event_type text NOT NULL DEFAULT 'Event',
    label_name text NOT NULL DEFAULT '',
    place_id bigint REFERENCES align_owner.saved_places(id) ON DELETE SET NULL
);

